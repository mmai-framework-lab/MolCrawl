"""mol_nl BERT medium -- batch 1024, learning rate 1.90e-04.

The molecule_nat_lang batch-size grid of the 2026-11-20 directive. Generated by
scripts/molnl_batch_sweep_configs.py from the derived arm inventory; edit the inventory
and regenerate rather than editing this file.

This arm's place in the grid. BERT runs 2 rates at this size and batch and keeps the lowest (§1, §10); this is number 2 of 2, against 1.33e-04.

The budget is fixed in blocks, not in steps (§2): 30,720,000 blocks of 1,024
tokens = 31,457,280,000 tokens = 96.57 epochs of the 318,118-block train split,
the same for all 48 BERT arms. At batch 1024 that is 30,000
steps, so the five batches cover the same data and their curves can be read at
the same block position.

The rate is this size's 2,560 rate scaled by sqrt(batch/2560) (§3): 1.0 x sqrt(1024/2560) x this size's 2,560 rate = 1.90e-04.

Warmup is 10 % of this arm's own length (§2), truncated: 3,000 of
30,000.

Evaluation lands every 122,880 blocks, which is 120
steps here, giving 250 points; saves land every 614,400 blocks, the same multiple of the evaluation interval at every batch.

One GPU takes 8 blocks and the accumulation count carries the rest (§4):
8 x 32 x 4 GPUs = 1024. Held across the five batches of this size, so what differs between them is the accumulation count and nothing else; §4 fixes it per size by measurement, and the whole 68 are regenerated when that measurement lands.

Everything not set below comes from bert_medium.py, imported rather than copied, so
this arm cannot differ from the 2026-09-24 grid and the 24,000-step runs in the corpus,
the tokenizer, the packing, the document masking, the dataloader or the precision.
"""

from molcrawl.tasks.pretrain.configs.molecule_nat_lang.bert_medium import *  # noqa: F401,F403
from molcrawl.core.paths import get_bert_output_path  # noqa: E402

# Per-arm directory. Unset, MODEL_OUTPUT_ROOT resolves under LEARNING_SOURCE_DIR -- the
# tree molnl's input and output already share -- and main.py's output guard stops the
# run before the first step. The name carries the batch and the rate, so no two arms of
# a size can write into one directory, where the first would be resumed by the second.
model_path = get_bert_output_path("molecule_nat_lang", model_size) + "-bert-b1024-lr1p9e4"  # noqa: F405

# §2. The budget in this arm's own steps, and the intervals that put every arm's points
# at the same block position. save_steps is 5 times the evaluation
# interval, so every checkpoint carries an evaluation.
max_steps = 30000
warmup_steps = 3000  # 10 % of max_steps
log_interval = 120  # main.py passes this to both logging_steps and eval_steps
save_steps = 600

# §3.
learning_rate = 0.00019

# §4. 8 x 32 x 4 GPUs = 1024.
batch_size = 8
gradient_accumulation_steps = 32
# §5. Declared so main.py stops a launch whose GPU count would build another batch.
expected_global_batch = 1024

# §6. The same masked positions at every evaluation, on every arm. The positions are
# reseeded from each evaluation batch's own bytes mixed with eval_mask_seed, so they
# only repeat when the rows fall into batches the same way -- which is why the
# evaluation micro-batch is held at 8 across the grid rather than following
# the training batch, and why the GPU count is fixed at 4.
#
# No evaluation subset is drawn. molnl's validation split is 1,631
# blocks and main.py's subsample_eval_split returns a split shorter than its
# 10,000-row cap unchanged, so every arm scores the whole split. eval_subset_random
# is deliberately not declared: on this split it would change nothing, and a config that
# named it would be the one thing that could move one arm's rows away from the others.
fixed_eval_mask = True
eval_mask_seed = 42
per_device_eval_batch_size = 8

# §7. The judged metric, and the same metric for the kept checkpoint and the ranking.
# All four names move together on purpose: the drift between them is what put HF's
# best-model marker on a different checkpoint from the adopted one in 9 of the 21 genome
# BERT runs. eval_loss and the per-position breakdown are still computed, still logged
# at every evaluation and still go into the reported TSV; they are not what the arm is
# ranked on.
judge_on = "eval_loss_mask"
metric_for_best_model = "eval_loss_mask"
save_on_improve_metric = "eval_loss_mask"
checkpoint_metric = "eval_loss_mask"
# Keep the checkpoint the reported number came from: the minimum lands off the save grid
# most of the time, and the arm would otherwise be ranked on a number whose weights no
# longer exist.
save_on_improve = True

# §8. Run the whole budget. A stop part-way would leave the five batches different
# lengths and nothing to compare at the same block position. Stated here because the
# default is now True and because an `import *` of a base that said False would be the
# only thing standing between this grid and an early stop.
early_stopping = False
seed = 42
max_length = 1024  # packed blocks; sets BertConfig.max_position_embeddings
document_masking = True
