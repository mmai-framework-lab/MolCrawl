"""Write the compounds batch-size grid's 68 configs from the derived arm inventory.

The inventory is the TSV ``compounds_batch_sweep_arms.py`` writes, which is itself
derived from the rules of the 2026-11-19c and 2026-11-20 directives and checked
against their printed tables. Writing the configs from that one source rather than by
hand is what keeps the 68 files consistent with the inventory that is reported, and it
makes the whole set reproducible from one command if a value in a directive changes.

That is what it was for. The 2026-11-20 directive changed two values -- batch 256
added (§1) and BERT judged on eval_loss_mask instead of eval_loss (§2) -- and the 48
BERT configs and 20 GPT-2 configs come out of one regeneration.

    compounds_batch_sweep_configs.py --arms rt1-...tsv [--out-dir <configs/compounds>]
    compounds_batch_sweep_configs.py --arms rt1-...tsv --check

``--check`` writes nothing: it reads the configs already on disk, evaluates each one
and compares every value it is supposed to carry against the inventory row. That is
the step that can fail, so it is the one worth running after a regeneration.

Nothing here launches anything.
"""

