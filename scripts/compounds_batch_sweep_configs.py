def check_all(rows, out_dir):
    problems = 0
    for row in rows:
        path = os.path.join(out_dir, os.path.basename(row["config"]))
        if not os.path.exists(path):
            print(f"  ** {os.path.basename(path)}: not written")
            problems += 1
            continue
        values = evaluate(path)
        for column, name in CHECKED[row["arch"]]:
            want = int(row[column])
            got = values.get(name)
            if got != want:
                print(f"  ** {os.path.basename(path)}: {name}={got!r} against "
                      f"inventory {column}={want}")
                problems += 1
        for name, want in CONSTANT[row["arch"]].items():
            got = values.get(name)
            if got != want:
                print(f"  ** {os.path.basename(path)}: {name}={got!r}, expected {want!r}")
                problems += 1
        want_lr = float(row["lr"])
        if values.get("learning_rate") != want_lr:
            print(f"  ** {os.path.basename(path)}: learning_rate="
                  f"{values.get('learning_rate')!r} against inventory {want_lr}")
            problems += 1
        if row["arch"] == "gpt2":
            want_min = float(row["min_lr"])
            if values.get("min_lr") != want_min:
                print(f"  ** {os.path.basename(path)}: min_lr={values.get('min_lr')!r} "
                      f"against inventory {want_min}")
                problems += 1
        if row["arch"] == "bert":
            want_threshold = float(row.get("degenerate_threshold")
                                   or BERT_DEGENERATE_THRESHOLD)
            if values.get("degenerate_loss_threshold") != want_threshold:
                print(f"  ** {os.path.basename(path)}: degenerate_loss_threshold="
                      f"{values.get('degenerate_loss_threshold')!r} against inventory "
                      f"{want_threshold}")
                problems += 1
            # Absent from the inventory means absent from the config: the 48 running
            # arms take main.py's own grace period, and a config that named it would be
            # a value changed under a run.
            want_grace = int(row["degenerate_grace_steps"]) if row.get(
                "degenerate_grace_steps") else None
            if values.get("degenerate_grace_steps") != want_grace:
                print(f"  ** {os.path.basename(path)}: degenerate_grace_steps="
                      f"{values.get('degenerate_grace_steps')!r} against inventory "
                      f"{want_grace!r}")
                problems += 1
            # The invariant is that no config names it at all, so this checks the text
            # rather than the value: the value would pass while the declaration is
            # what breaks the shared subset.
            source = open(path, encoding="utf-8").read()
            if any(line.startswith("eval_subset_seed")
                   for line in source.splitlines()):
                print(f"  ** {os.path.basename(path)}: declares eval_subset_seed; the "
                      f"subset seed is one constant in main.py")
                problems += 1
        suffix = f"-b{row['batch']}-lr{row['lr_slug']}"
        target = values.get("model_path") or values.get("out_dir") or ""
        if not str(target).endswith(suffix):
            print(f"  ** {os.path.basename(path)}: output {target!r} does not end "
                  f"{suffix!r}")
            problems += 1
    return problems


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--arms", required=True, help="the derived arm inventory TSV")
    ap.add_argument("--out-dir", default=DEFAULT_OUT_DIR)
    ap.add_argument("--check", action="store_true",
                    help="write nothing; read the configs on disk and compare")
    args = ap.parse_args(argv)

    rows = read_arms(args.arms)
    print(f"=== {len(rows)} arms from {args.arms} ===")
    if not args.check:
        written = write_all(rows, args.out_dir)
        print(f"wrote {len(written)} configs into {args.out_dir}")
        for arch in ("bert", "gpt2"):
            n = sum(1 for r in rows if r["arch"] == arch)
            print(f"  {arch}: {n}")

    print("\n=== configs against the inventory ===")
    problems = check_all(rows, args.out_dir)
    checks = sum(len(CHECKED[r["arch"]]) + len(CONSTANT[r["arch"]]) + 2 for r in rows)
    print(f"  {checks} values compared over {len(rows)} configs")
    print(f"disagreements: {problems}")
    return 0 if problems == 0 else 1


