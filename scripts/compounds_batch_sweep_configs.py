def grace_block(row):
    """The grace-period lines, for a row that carries one.

    Returned as text appended to the threshold line rather than as a separate
    placeholder, so a row without a grace period renders exactly the file it rendered
    before this was added.
    """
    grace = row.get("degenerate_grace_steps")
    if not grace:
        return ""
    grace = int(grace)
    rows = grace * int(row["batch"])
    return (
        f"\n# How long to wait before the rule above can fire. MLM sits at the "
        f"degenerate\n"
        f"# level for a while at the start, so a short wait reads that plateau as a "
        f"collapse.\n"
        f"# The wait is a number of blocks, not a number of steps, so every batch "
        f"waits over\n"
        f"# the same amount of data (2026-11-27 judgment §4): {GRACE_ROWS:,} blocks, "
        f"10 % of the\n"
        f"# budget, which at batch {int(row['batch'])} is {grace:,} of this arm's "
        f"{int(row['steps']):,} steps\n"
        f"# ({rows:,} blocks once truncated, as the warmup is).\n"
        f"degenerate_grace_steps = {grace}"
    )


def read_arms(path):
    with open(path, newline="", encoding="utf-8") as handle:
        lines = [line for line in handle if not line.startswith("#")]
    rows = list(csv.DictReader(lines, delimiter="\t"))
    if not rows:
        raise SystemExit(f"{path}: no arm rows")
    return rows


def arm_place(row, siblings):
    """One sentence on what else shares this arm's size and batch."""
    rates = sorted(float(r["lr"]) for r in siblings)
    if len(rates) == 1:
        return (f"GPT-2 runs one rate per batch (§3), so this is the whole of "
                f"{row['size']} at batch {row['batch']}.")
    place = rates.index(float(row["lr"])) + 1
    others = ", ".join(f"{r:.2e}" for r in rates if r != float(row["lr"]))
    return (f"BERT runs {len(rates)} rates at this size and batch and keeps the "
            f"lowest (§3); this is number {place} of {len(rates)}, against {others}.")


def fields(row, siblings):
    arch = row["arch"]
    batch = int(row["batch"])
    steps = int(row["steps"])
    lr = float(row["lr"])
    eval_interval = int(row["eval_interval"])
    warmup = int(row["warmup_steps"])
    micro = int(row["micro_batch"])
    world = int(row["world_size"])
    out_suffix = f"-b{batch}-lr{row['lr_slug']}"
    base = {
        "arch_label": "BERT" if arch == "bert" else "GPT-2",
        # The BERT count grew from 48 to 90 with the 2026-11-27b additions; a row
        # that does not say carries the grid as it was launched.
        "arch_arms": row.get("arch_arms") or ("48" if arch == "bert" else "20"),
        # Which directives this arm's values come from. A row that does not say is one
        # of the 68 the grid was launched with.
        "directives": (row.get("directives")
                       or "the 2026-11-19c and 2026-11-20 directives"),
        "size": row["size"],
        "batch": batch,
        "lr": f"{lr:.2e}",
        "lr_literal": repr(lr),
        "arm_place": arm_place(row, siblings),
        "rows": int(row["rows"]),
        "tokens": int(row["tokens"]),
        "block_size": BLOCK_SIZE,
        "steps": steps,
        "step_word": "steps" if arch == "bert" else "iterations",
        "lr_reason": (f"{row['lr_multiplier']} x sqrt({batch}/2560) x this size's "
                      f"2,560 rate = {lr:.2e}."),
        "warmup": warmup,
        "warmup_pct": "10 %" if arch == "bert" else "2 %",
        "micro": micro,
        "grad_accum": int(row["grad_accum"]),
        "world_size": world,
        "world_term": f" x {world} GPUs" if world != 1 else "",
        "micro_note": ("Held across the five batches, so what differs between them is "
                       "the accumulation count and nothing else."),
        "eval_interval": eval_interval,
        "eval_points": steps // eval_interval,
        "seed": SEED,
        "out_suffix": out_suffix,
    }
    if arch == "bert":
        save_interval = int(row["save_interval"])
        base.update({
            "save_interval": save_interval,
            "save_points": steps // save_interval,
            "weight_decay": BERT_WEIGHT_DECAY,
            "workers": BERT_DATALOADER_WORKERS,
            "ddp_timeout": BERT_DDP_TIMEOUT,
            "degenerate": float(row.get("degenerate_threshold")
                                or BERT_DEGENERATE_THRESHOLD),
            "degenerate_extra": grace_block(row),
            "eval_batch": int(row["eval_batch"]),
            "eval_mask_seed": SEED,
            "eval_subset_seed": EVAL_SUBSET_SEED,
            "judge_metric": BERT_JUDGE_METRIC,
        })
    else:
        base.update({
            "lr_decay_iters": int(row["lr_decay_iters"]),
            "min_lr_literal": repr(float(row["min_lr"])),
            "log_interval": max(1, eval_interval // GPT2_LOG_DIVISOR),
            "save_checkpoint_steps": eval_interval * GPT2_SAVE_MULTIPLE,
            "max_checkpoints": GPT2_MAX_CHECKPOINTS,
            "eval_sequences": GPT2_EVAL_SEQUENCES,
            "weight_decay": GPT2_WEIGHT_DECAY,
        })
    return base


def render(row, siblings):
    values = fields(row, siblings)
    values["header"] = HEADER.format(**values)
    body = BERT_BODY if row["arch"] == "bert" else GPT2_BODY
    return body.format(**values)


def siblings_of(rows, row):
    return [r for r in rows
            if r["arch"] == row["arch"] and r["size"] == row["size"]
            and r["batch"] == row["batch"]]


def write_all(rows, out_dir):
    written = []
    for row in rows:
        text = render(row, siblings_of(rows, row))
        name = os.path.basename(row["config"])
        path = os.path.join(out_dir, name)
        with open(path, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(text)
        written.append(path)
    return written


def evaluate(path):
    """The config's top-level names, without importing the repository."""
    namespace = {"__file__": path, "__name__": "config_under_check"}
    source = open(path, encoding="utf-8").read()
    # The two imports reach into the repository; the values this checks do not come
    # from them, so they are stubbed rather than executed.
    stub = ("class _T:\n"
            "    def __init__(self, *a, **k):\n"
            "        self.vocab_size = 0\n"
            "        self.eos_token_id = 0\n"
            "Tokenizer = _T\n"
            "COMPOUNDS_DATASET_DIR_BERT = COMPOUNDS_DATASET_DIR_GPT2 = ''\n"
            "def get_bert_output_path(*a, **k):\n"
            "    return '/'.join(a)\n"
            "get_gpt2_output_path = get_bert_output_path\n")
    kept = "\n".join(line for line in source.splitlines()
                     if not line.startswith("from molcrawl"))
    exec(compile(stub + kept, path, "exec"), namespace)  # noqa: S102
    return namespace


