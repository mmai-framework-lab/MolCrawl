"""Write the rna batch-size grid's 68 configs from the derived arm inventory.

Generated rather than hand-written: the grid differs between arms in eight values
that all follow from the batch, and 68 files edited by hand is 68 chances to put one
of them in the wrong row. Regenerate from the inventory instead of editing a file
here; --check says whether what is on disk still matches it.

Each arm sits on the adopted 2,560 arm of its own size and overrides only what the
directive moves. Importing that config rather than copying it keeps the corpus, the
tokenizer, the split, the mask rate, the sequence length and the document masking
identical to the run this grid is compared against -- §8's list of what must not
change is then not a thing to remember but a thing that cannot be edited here.

    rna_batch_sweep_configs.py --arms rt1-...tsv [--check] [--configs-dir ...]
"""

from __future__ import annotations

import argparse
import csv
import os
import sys

#: The adopted 2,560 arm each size's grid sits on (§3's basis).
PARENT = {
    ("bert", "small"): "bert_small_lr3e4",
    ("bert", "medium"): "bert_medium_lr3e4",
    ("bert", "large"): "bert_large_lr1p7e4",
    ("bert", "xl"): "bert_xl_lr2p5e5",
    ("gpt2", "small"): "gpt2_small_lr1p2e3_9ep",
    ("gpt2", "medium"): "gpt2_medium_lr1p2e3_9ep",
    ("gpt2", "large"): "gpt2_large_lr6e4_9ep",
    ("gpt2", "xl"): "gpt2_xl_lr6e4_9ep",
}

HEADER = """# rna {arch_label} {size} -- batch {batch}, lr {lr}
# The rna batch-size grid of the 2026-11-20 directive. Generated by
# scripts/rna_batch_sweep_configs.py from the derived arm inventory; edit the
# inventory and regenerate rather than editing this file.
#
# {place}
#
# The budget is fixed in blocks, not in steps (§2): {blocks} packed blocks of
# 1,024 tokens = {tokens} tokens, the same for all 68 arms and the same as the
# existing grid's 120,960 x 2,560. At batch {batch} that is {steps} steps, so the
# five batches cover the same data and their curves meet at the same block.
#
# The rate is this size's adopted 2,560 rate scaled by sqrt(batch / 2560) (§3):
# {multiplier} x sqrt({batch}/2560) x {base_lr} = {lr}.
#
# Warmup is {warmup_pct} of this arm's own length (§2), truncated: {warmup} of
# {steps}.
#
# One GPU takes {micro} blocks and the accumulation count carries the rest (§4):
# {shape}. Held across the five batches of this size, so what differs between
# them is the accumulation count and nothing else.
{extra_notes}
# Everything else comes from {parent}.py, imported rather than copied, so the
# corpus, the tokenizer, the split, the mask rate, the sequence length, the
# document masking and the seed are the adopted arm's own (§8).

from molcrawl.tasks.pretrain.configs.rna.{parent} import *  # noqa: F401,F403
"""

BERT_BODY = """
max_steps = {steps}
warmup_steps = {warmup}  # {warmup_pct} of max_steps (§2)
learning_rate = {lr}
# Pretraining runs the whole schedule (§8): a stop part-way would leave the five
# curves different lengths and nothing to compare.
early_stopping = False

# {eval_points} evaluation points and {save_points} save points, at the same block
# positions as every other batch in the grid (§2). save_steps is a multiple of the
# evaluation interval, so every checkpoint carries an evaluation.
log_interval = {eval_interval}  # = eval_steps
save_steps = {save_interval}
# Keep the checkpoint the reported number came from: the minimum lands off the save
# grid most of the time, and the arm would otherwise be ranked on a number whose
# weights no longer exist.
save_on_improve = True

# The judged metric, and the same metric for the kept checkpoint (§7).
judge_on = "eval_loss_mask"
metric_for_best_model = "eval_loss_mask"
save_on_improve_metric = "eval_loss_mask"
checkpoint_metric = "eval_loss_mask"

# The same masked positions at every evaluation, on every arm (§6). The positions
# are drawn from the batch's own contents mixed with eval_mask_seed, so they only
# repeat while the rows are grouped the same way -- which is why the evaluation
# micro-batch and the GPU count are held at {eval_batch} and 4 across the grid
# instead of following the training batch.
fixed_eval_mask = True
eval_mask_seed = 42
per_device_eval_batch_size = {eval_batch}
# The subset seed is deliberately not written here: the rows come from one constant,
# EVAL_SUBSET_SEED in models/bert/main.py, which is already the 42 §6 asks for, and
# rna is shuffled in prep so the leading rows it takes are already a random sample.

# {shape} (§4).
batch_size = {micro}
gradient_accumulation_steps = {accum}
# Declared so main.py stops a launch whose GPU count would build another batch (§5).
expected_global_batch = {batch}
"""

GPT2_BODY = """
max_iters = {steps}
lr_decay_iters = {steps}  # the decay length is this arm's own run (§8)
warmup_iters = {warmup}  # {warmup_pct} of max_iters (§2)
learning_rate = {lr}
min_lr = {min_lr}  # a tenth of this arm's own peak (§8)
# Pretraining runs the whole schedule (§8). train.py's own default is True with a
# patience of 10, so leaving this out would stop an arm part-way.
early_stopping = False

# {eval_points} evaluation points, at the same block positions as every other batch
# in the grid (§2).
eval_interval = {eval_interval}
# nanoGPT writes ckpt.pt whenever the validation loss improves, which is what keeps
# the reported minimum's weights (§4 of the extension directive); there is no save
# interval to set.

# {shape} (§4). nanoGPT divides the accumulation count across the four ranks, so the
# global batch is micro x accumulation with no GPU factor.
batch_size = {micro}
gradient_accumulation_steps = {accum}
# Declared so train.py stops a launch whose shape would build another batch (§5).
expected_global_batch = {batch}
"""

BERT_TAIL = """
# Per-arm directory under MODEL_OUTPUT_ROOT. Unset, this resolves under
# LEARNING_SOURCE_DIR -- the tree rna's input and output already share -- and
# main.py's output guard stops the run before its first step. The launch points the
# root away from the trees the 18-epoch extension writes.
model_path = get_bert_output_path("rna", "{size}") + "-b{batch}-lr{slug}"
"""

GPT2_TAIL = """
import os as _os  # noqa: E402

_runs_root = _os.environ.get("MODEL_OUTPUT_ROOT")
if not _runs_root:
    raise SystemExit(
        "set MODEL_OUTPUT_ROOT to a runs root outside any input tree; "
        "deriving it from LEARNING_SOURCE_DIR puts checkpoints beside the corpus"
    )
out_dir = _os.path.join(_runs_root, "{out_dir}")
tensorboard_dir = out_dir
"""

DETECTOR = """
# Stop an arm that has fallen to the degenerate solution instead of letting it spend
# the rest of a long schedule there. 9.0 is measured for rna: the 14 arms of the
# existing grid that ended collapsed sit at a median of 9.3737 at the lowest and the
# unigram floor is 9.3710, while a healthy arm is below 9.0 well before the grace
# window ends. The grace window is in this arm's own steps, from the block position a
# healthy arm is past the threshold by, because it is compared against the absolute
# step count and the five batches differ 16-fold.
degenerate_loss_threshold = {threshold}
degenerate_patience = {patience}
degenerate_grace_steps = {grace}
"""


def fmt(value: str) -> str:
    """A rate as a config writes it: 9.49e-05 rather than 9.49e-5."""
    return f"{float(value):.6g}"


def render(row: dict) -> str:
    arch, size = row["arch"], row["size"]
    parent = PARENT[(arch, size)]
    rates = int(row["rates_at_this_batch"])
    rank = int(row["rate_rank"])
    if arch == "bert":
        place = (f"This arm's place in the grid. BERT runs {rates} rates at this size"
                 f" and batch and keeps the lowest (§3); this is number {rank} of"
                 f" {rates}.")
    else:
        place = "GPT-2 runs one rate per batch (§3), so this arm is the batch."
    shape = (f"{row['micro_batch']} x {row['grad_accum']} x 4 GPUs ="
             f" {row['batch']}" if arch == "bert" else
             f"{row['micro_batch']} x {row['grad_accum']} = {row['batch']}")
    extra = ""
    if arch == "gpt2" and parent.endswith("_9ep"):
        extra = ("#\n# The adopted arm fixes its validation rows"
                 " (deterministic_val_eval), and §6 leaves GPT-2's evaluation alone,"
                 " so that carries through the import.\n")
    text = HEADER.format(
        arch_label="BERT" if arch == "bert" else "GPT-2", size=size,
        batch=row["batch"], lr=fmt(row["lr"]), place=place,
        blocks=f"{int(row['blocks']):,}", tokens=f"{int(row['tokens']):,}",
        steps=f"{int(row['steps']):,}", multiplier=row["lr_multiplier"],
        base_lr=f"{float(row['lr']) / float(row['lr_multiplier']) / (int(row['batch']) / 2560) ** 0.5:.3g}",
        warmup_pct="10 %" if arch == "bert" else "2 %",
        warmup=f"{int(row['warmup_steps']):,}", micro=row["micro_batch"],
        shape=shape, extra_notes=extra, parent=parent)
    body = BERT_BODY if arch == "bert" else GPT2_BODY
    text += body.format(
        steps=row["steps"], warmup=row["warmup_steps"], lr=fmt(row["lr"]),
        warmup_pct="10 %" if arch == "bert" else "2 %",
        eval_interval=row["eval_interval"], save_interval=row["save_interval"],
        eval_points=row["eval_points"], save_points=row["save_points"],
        eval_batch=row["eval_batch"], micro=row["micro_batch"],
        accum=row["grad_accum"], batch=row["batch"], shape=shape,
        min_lr=fmt(row["min_lr"]) if row["min_lr"] else "")
    if arch == "bert" and row["degenerate_loss_threshold"]:
        text += DETECTOR.format(threshold=row["degenerate_loss_threshold"],
                                patience=row["degenerate_patience"],
                                grace=row["degenerate_grace_steps"])
    if arch == "bert":
        text += BERT_TAIL.format(size=size, batch=row["batch"], slug=row["lr_slug"])
    else:
        text += GPT2_TAIL.format(out_dir=row["out_dir"])
    return text


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--arms", required=True, help="the derived arm inventory TSV")
    ap.add_argument("--configs-dir", default="molcrawl/tasks/pretrain/configs/rna")
    ap.add_argument("--check", action="store_true",
                    help="compare what is on disk against the inventory and write nothing")
    args = ap.parse_args()

    with open(args.arms, encoding="utf-8") as handle:
        rows = list(csv.DictReader(
            (ln for ln in handle if not ln.startswith("#")), delimiter="\t"))
    if not rows:
        print("the inventory is empty", file=sys.stderr)
        return 2

    written, same, differ, missing = 0, 0, [], []
    for row in rows:
        path = os.path.join(args.configs_dir, os.path.basename(row["config"]))
        text = render(row)
        if args.check:
            if not os.path.exists(path):
                missing.append(path)
            elif open(path, encoding="utf-8").read() == text:
                same += 1
            else:
                differ.append(path)
            continue
        os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as out:
            out.write(text)
        written += 1

    if args.check:
        print(f"=== {len(rows)} arms: {same} match, {len(differ)} differ,"
              f" {len(missing)} missing")
        for path in differ + missing:
            print(f"    - {path}")
        return 1 if differ or missing else 0

    print(f"=== wrote {written} configs under {args.configs_dir}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
