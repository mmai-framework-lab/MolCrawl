def preprocess_function(examples):
    """Add attention_mask for BERT compatibility."""
    if "input_ids" in examples:
        input_ids = examples["input_ids"]
        pad_id = getattr(tokenizer, "pad_token_id", None)
        pad_id = pad_id if pad_id is not None else 0
        if isinstance(input_ids[0], list):
            examples["attention_mask"] = [[1 if t != pad_id else 0 for t in seq] for seq in input_ids]
        else:
            examples["attention_mask"] = [1 if t != pad_id else 0 for t in input_ids]
    return examples


class ProteinSequenceDataCollator(DataCollatorForLanguageModeling):
    """Protein collator that renames sequence_tokens -> input_ids before masking."""

    def torch_call(self, examples: List[Dict[str, Any]]) -> Dict[str, torch.Tensor]:
        for example in examples:
            if "sequence_tokens" in example and "input_ids" not in example:
                example["input_ids"] = example.pop("sequence_tokens")
        return super().torch_call(examples)


# Mask rate 0.2, through the protein collator (section 8); not settable from main.py.
