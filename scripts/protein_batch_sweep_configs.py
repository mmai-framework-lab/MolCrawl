"""Write the protein batch-size grid's configs from the derived arm inventory, and
check what is on disk against that inventory.

The inventory is scripts/protein_batch_sweep_arms.py's TSV. Writing the configs from
that one source keeps every file consistent with the numbers that get reported, and
makes the whole set reproducible if a directive value changes.

    protein_batch_sweep_configs.py --arms rt1-...tsv [--out-dir <configs/protein_sequence>]
    protein_batch_sweep_configs.py --arms rt1-...tsv --check

--check writes nothing: it parses each config on disk and compares the values it is
supposed to carry against the inventory row.

Protein specifics kept from the base configs (NOT the compounds grid):
  * BERT masks through ProteinSequenceDataCollator(mlm_probability=0.2), defined inline.
  * adam_beta2 = 0.999 on BERT (0.95 collapses protein -- base config note).
  * degenerate_loss_threshold = None (collapse detector off for protein; the run goes
    the whole budget, section 8).
  * ESM tokenizer and the UNIPROT paths.
Nothing here launches anything.
"""
from __future__ import annotations

import argparse
import ast
import csv
import os

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
DEFAULT_OUT_DIR = os.path.join(REPO, "molcrawl", "tasks", "pretrain", "configs", "protein_sequence")

SEED = 42
BLOCK_SIZE = 1024
EVAL_MASK_SEED = 42
BERT_JUDGE = "eval_loss_mask"
BERT_WEIGHT_DECAY = 0.01
BERT_ADAM_BETA2 = 0.999
GPT2_WEIGHT_DECAY = 0.1
