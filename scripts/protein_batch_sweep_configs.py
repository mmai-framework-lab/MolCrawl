# Budget fixed in columns, not steps (section 2): {rows:,} packed blocks of {block_size}
# tokens = {tokens:,} tokens, the same for every arm. At batch {batch} that is {steps:,}
# {step_word}, so the five batches cover the same data and compare at the same column.
#
# Rate = this size's 2,560 rate x sqrt(batch/2560){mult_term} (section 3){rate_extra}.
# Warmup {warmup_pct} of this arm's length, truncated: {warmup:,} of {steps:,} (section 2).
