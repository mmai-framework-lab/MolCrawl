# §4. nanoGPT divides gradient_accumulation_steps by the DDP world size, so the
# effective global batch is batch_size x gradient_accumulation_steps and does not move
# with the GPU count. {micro} x {grad_accum} = {batch}.
batch_size = {micro}
gradient_accumulation_steps = {grad_accum}
# §5. train.py refuses to start when micro x accumulation disagrees with this.
expected_global_batch = {batch}

# §2. {eval_points} evaluation points, every {eval_blocks:,} blocks. The training loss
# is logged every {log_interval} iteration(s), which divides the evaluation window, so
# every validation point has a training point at the same block position.
eval_interval = {eval_interval}
log_interval = {log_interval}

# §6 asks for GPT-2's evaluation to be left alone because its validation set is already
# deterministic. On molnl it is not: train.py's default resamples the validation batches
# with replacement at every evaluation, and on this corpus that put 0.017 to 0.022 of
# noise on each point -- larger than the differences between sizes, and larger than the
# differences this grid is meant to resolve. The 2026-10-14 order §2 already fixed
# molnl's GPT-2 validation set for exactly that reason, and the fixed-val configs it
# produced are what the reported molnl GPT-2 curves come from. So the grid holds it
# fixed too, and §6's sentence is answered rather than followed to the letter.
#
# eval_sequences fixes the number of validation *sequences* rather than batches, so
