def read_arms(path):
    with open(path, newline="", encoding="utf-8") as handle:
        lines = [line for line in handle if not line.startswith("#")]
    rows = list(csv.DictReader(lines, delimiter="\t"))
    if not rows:
        raise SystemExit(f"{path}: no arm rows")
    return rows


def arm_place(row, siblings):
    """One sentence on what else shares this arm's size and batch."""
    rates = sorted(float(r["lr"]) for r in siblings)
    if len(rates) == 1:
        return (f"GPT-2 runs one rate per batch (§1), so this is the whole of "
                f"{row['size']} at batch {row['batch']}.")
    place = rates.index(float(row["lr"])) + 1
    others = ", ".join(f"{r:.2e}" for r in rates if r != float(row["lr"]))
    return (f"BERT runs {len(rates)} rates at this size and batch and keeps the lowest "
            f"(§1, §10); this is number {place} of {len(rates)}, against {others}.")


def fields(row, siblings):
    arch = row["arch"]
    batch = int(row["batch"])
    steps = int(row["steps"])
    lr = float(row["lr"])
    eval_interval = int(row["eval_interval"])
    save_interval = int(row["save_interval"])
    micro = int(row["micro_batch"])
    world = int(row["world_size"])
    size = row["size"]
    out_size = "ex-large" if (arch == "gpt2" and size == "xl") else size
    # Carries the architecture; see the comment on out_dir in
    # scripts/molnl_batch_sweep_arms.py for why this modality needs it.
    out_suffix = f"-{arch}-b{batch}-lr{row['lr_slug']}"
    base = {
        # Which set one GPU's block count came from. Stated in the file because it is
        # the one value of the inventory that a reader cannot recover from the numbers
        # below, and because the check that compares these configs against the
        # inventory has to derive the same set to compare against.
        "micro_batch_set": row["micro_batch_set"],
        "arch_label": "BERT" if arch == "bert" else "GPT-2",
        "arch_arms": "48" if arch == "bert" else "20",
        "size": size,
        "base_module": f"{'bert' if arch == 'bert' else 'gpt2'}_{size}",
        "batch": batch,
        "lr": f"{lr:.2e}",
        "lr_literal": repr(lr),
        "arm_place": arm_place(row, siblings),
        "blocks": int(row["blocks"]),
        "tokens": int(row["tokens"]),
        "epochs": row["epochs"],
        "train_blocks": 318_118,
        "block_size": BLOCK_SIZE,
        "steps": steps,
        "step_word": "steps" if arch == "bert" else "iterations",
        "step_word_short": "steps" if arch == "bert" else "iterations",
        "lr_reason": (f"{row['lr_multiplier']} x sqrt({batch}/2560) x this size's 2,560 "
                      f"rate = {lr:.2e}."),
        "warmup": int(row["warmup_steps"]),
        "warmup_pct": "10 %" if arch == "bert" else "2 %",
        "micro": micro,
        "grad_accum": int(row["grad_accum"]),
        "world_size": world,
        "world_term": f" x {world} GPUs" if world != 1 else "",
        "micro_note": ("Held across the five batches of this size, so what differs "
                       "between them is the accumulation count and nothing else; §4 "
                       "fixes it per size by measurement, and the whole 68 are "
                       "regenerated when that measurement lands."),
        "eval_interval": eval_interval,
        "save_interval": save_interval,
        "save_multiple": save_interval // eval_interval,
        "eval_points": int(row["eval_points"]),
        "eval_blocks": eval_interval * batch,
        "seed": SEED,
        "out_suffix": out_suffix,
    }
    if arch == "bert":
        base.update({
            "eval_batch": int(row["eval_batch"]),
            "eval_blocks_count": int(row["eval_blocks"]),
            "subset_cap": 10_000,
            "eval_mask_seed": BERT_EVAL_MASK_SEED,
            "judge_metric": BERT_JUDGE_METRIC,
            "save_note": (f"saves land every {save_interval * batch:,} blocks, the same "
                          f"multiple of the evaluation interval at every batch."),
        })
    else:
        base.update({
            "lr_decay_iters": int(row["lr_decay_iters"]),
            "min_lr_literal": repr(float(row["min_lr"])),
            "log_interval": max(1, eval_interval // GPT2_LOG_DIVISOR),
            "max_checkpoints": GPT2_MAX_CHECKPOINTS,
            "eval_sequences": GPT2_EVAL_SEQUENCES,
            "judge_metric": GPT2_JUDGE_METRIC,
            "save_note": (f"checkpoint opportunities land every "
                          f"{save_interval * batch:,} blocks."),
        })
        base["out_size"] = out_size
    return base


def render(row, siblings):
    values = fields(row, siblings)
    values["header"] = HEADER.format(**values)
    body = BERT_BODY if row["arch"] == "bert" else GPT2_BODY
    return body.format(**values)


def siblings_of(rows, row):
    return [r for r in rows
            if r["arch"] == row["arch"] and r["size"] == row["size"]
            and r["batch"] == row["batch"]]


def write_all(rows, out_dir):
    written = []
    for row in rows:
        text = render(row, siblings_of(rows, row))
        path = os.path.join(out_dir, os.path.basename(row["config"]))
        with open(path, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(text)
        written.append(path)
    return written


def evaluate(path):
    """The config's resolved names, run the way the launcher runs it.

    bert-grid.sbatch and molnl-batch-sweep-gpt2.sbatch both read a config with
    runpy.run_path before the allocation is put to work, so checking it the same way
    checks what they will see -- including anything the `import *` brings in.
    """
    sys.path.insert(0, REPO)
    return runpy.run_path(path)


#: (inventory column, config name) pairs that must agree, per framework.
CHECKED = {
    "bert": [("steps", "max_steps"), ("warmup_steps", "warmup_steps"),
             ("eval_interval", "log_interval"), ("save_interval", "save_steps"),
             ("micro_batch", "batch_size"),
             ("grad_accum", "gradient_accumulation_steps"),
             ("expected_global_batch", "expected_global_batch"),
             ("eval_batch", "per_device_eval_batch_size")],
    "gpt2": [("steps", "max_iters"), ("warmup_steps", "warmup_iters"),
             ("eval_interval", "eval_interval"),
             ("save_interval", "save_checkpoint_steps"),
             ("lr_decay_iters", "lr_decay_iters"),
             ("micro_batch", "batch_size"),
             ("grad_accum", "gradient_accumulation_steps"),
             ("expected_global_batch", "expected_global_batch")],
}
#: Config names that must hold these exact values on every arm of the framework.
CONSTANT = {
    "bert": {"seed": SEED, "early_stopping": False, "fixed_eval_mask": True,
             "eval_mask_seed": BERT_EVAL_MASK_SEED,
             "judge_on": BERT_JUDGE_METRIC,
             "metric_for_best_model": BERT_JUDGE_METRIC,
             "save_on_improve_metric": BERT_JUDGE_METRIC,
             "checkpoint_metric": BERT_JUDGE_METRIC, "save_on_improve": True,
             "document_masking": True, "bf16": True, "max_length": BLOCK_SIZE,
             "dataloader_num_workers": 4, "dataloader_pin_memory": True},
    "gpt2": {"seed": SEED, "early_stopping": False, "block_size": BLOCK_SIZE,
             "deterministic_val_eval": True, "eval_sequences": GPT2_EVAL_SEQUENCES,
             "always_save_checkpoint": False, "init_from": "scratch",
             "dtype": "bfloat16", "max_checkpoints": GPT2_MAX_CHECKPOINTS},
}


def check_all(rows, out_dir):
    problems = 0
    compared = 0
    for row in rows:
        path = os.path.join(out_dir, os.path.basename(row["config"]))
        name = os.path.basename(path)
        if not os.path.exists(path):
            print(f"  ** {name}: not written")
            problems += 1
            continue
        try:
            values = evaluate(path)
        except Exception as exc:  # noqa: BLE001 -- the launcher would fail the same way
            print(f"  ** {name}: does not execute: {type(exc).__name__}: {exc}")
            problems += 1
            continue
        for column, key in CHECKED[row["arch"]]:
            want = int(row[column])
            got = values.get(key)
            compared += 1
            if got != want:
                print(f"  ** {name}: {key}={got!r} against inventory {column}={want}")
                problems += 1
        for key, want in CONSTANT[row["arch"]].items():
            got = values.get(key)
            compared += 1
            if got != want:
                print(f"  ** {name}: {key}={got!r}, expected {want!r}")
                problems += 1
        want_lr = float(row["lr"])
        compared += 1
        if values.get("learning_rate") != want_lr:
            print(f"  ** {name}: learning_rate={values.get('learning_rate')!r} against "
                  f"inventory {want_lr}")
            problems += 1
        if row["arch"] == "gpt2":
            want_min = float(row["min_lr"])
            compared += 1
            if values.get("min_lr") != want_min:
                print(f"  ** {name}: min_lr={values.get('min_lr')!r} against inventory "
                      f"{want_min}")
                problems += 1
        if row["arch"] == "bert":
            # The invariant is that no arm declares it at all: on a 1,631-block split
            # the value changes nothing, but a declaration is what could move one arm's
            # rows away from the others, and the check is on the text for that reason.
            compared += 1
            if any(line.startswith("eval_subset_random")
                   or line.startswith("eval_subset_seed")
                   for line in open(path, encoding="utf-8").read().splitlines()):
                print(f"  ** {name}: declares an eval subset; molnl scores the whole "
                      f"validation split")
                problems += 1
            # Proof that the base reached this file: main.py applies it to both splits
            # when a config defines one, and a config that failed to inherit it would
            # train on input prepared differently from every molnl run so far.
            compared += 1
            if not callable(values.get("preprocess_function")):
                print(f"  ** {name}: preprocess_function did not come through the "
                      f"import; the input would be prepared differently")
                problems += 1
        suffix = f"-b{row['batch']}-lr{row['lr_slug']}"
        target = values.get("model_path") or values.get("out_dir") or ""
        compared += 1
        if not str(target).endswith(suffix):
            print(f"  ** {name}: output {target!r} does not end {suffix!r}")
            problems += 1
        if row["arch"] == "gpt2":
            compared += 1
            if values.get("tensorboard_dir") != values.get("out_dir"):
                print(f"  ** {name}: tensorboard_dir {values.get('tensorboard_dir')!r} "
                      f"is not out_dir {values.get('out_dir')!r}")
                problems += 1
    return problems, compared


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--arms", required=True, help="the derived arm inventory TSV")
    ap.add_argument("--out-dir", default=DEFAULT_OUT_DIR)
    ap.add_argument("--check", action="store_true",
                    help="write nothing; execute the configs on disk and compare")
    args = ap.parse_args(argv)

    rows = read_arms(args.arms)
    print(f"=== {len(rows)} arms from {args.arms} ===")
    if not args.check:
        written = write_all(rows, args.out_dir)
        print(f"wrote {len(written)} configs into {args.out_dir}")
        for arch in ("bert", "gpt2"):
            n = sum(1 for r in rows if r["arch"] == arch)
            print(f"  {arch}: {n}")

    print("\n=== configs against the inventory ===")
    problems, compared = check_all(rows, args.out_dir)
    print(f"  {compared} values compared over {len(rows)} configs")
    print(f"disagreements: {problems}")
    return 0 if problems == 0 else 1


if __name__ == "__main__":
    raise SystemExit(main())
